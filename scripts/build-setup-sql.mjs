#!/usr/bin/env node
// Builds supabase/setup_all.sql = every migration (in order) + accounts.sql,
// so the whole backend can be set up by pasting ONE file into Supabase → SQL Editor.
//   npm run build-setup-sql
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
const dir = 'supabase/migrations';
const parts = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()
  .map((f) => `-- ======================== ${f} ========================\n${readFileSync(`${dir}/${f}`, 'utf8')}`);
const head = `-- Our Bucket List — COMPLETE SETUP (generated by scripts/build-setup-sql.mjs; do not edit by hand).
-- Paste this whole file into Supabase → SQL Editor and press Run.
--  1. Creates/updates all tables, privacy rules and storage buckets (safe to re-run; keeps existing data).
--  2. Creates/updates the two accounts and shows your two PERSONAL LINKS in the results.
-- Before running: search for YOUR-SITE below and put your site address there.\n\n`;
writeFileSync('supabase/setup_all.sql', head + parts.join('\n\n') + '\n\n-- ======================== accounts.sql ========================\n' + readFileSync('supabase/accounts.sql', 'utf8'));
console.log('wrote supabase/setup_all.sql');
